def _load_category(module_name, list_name, category_label):
    try:
        mod = __import__(module_name)
        lst = getattr(mod, list_name)
        existing = {r["name"] for r in RECIPES}
        added = 0
        for r in lst:
            if r["name"] not in existing:
                r.setdefault("category", category_label)
                RECIPES.append(r)
                existing.add(r["name"])
                added += 1
        print("[i] " + category_label + ": +" + str(added) + " рецептов")
        return added
    except (ImportError, AttributeError) as e:
        print("[!] " + category_label + ": модуль не найден (" + module_name + ")")
        return 0


