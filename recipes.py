def normalize(text):
    return re.sub(r"[^а-яёa-z0-9 ]", "", text.lower().strip())


def split_products(user_input):
    user_input = user_input.replace(";", ",").replace("\n", ",")
    raw = re.split(r"[,\s]+", user_input)
    products = set()
    for item in raw:
        item = normalize(item)
        if item:
            products.add(item)
    return products


def find_matches(products):
    results = []
    for recipe in RECIPES:
        needed = {normalize(x) for x in recipe["ingredients"]}
        have = products & needed
        missing = needed - have
        if not have:
            continue
        match_percent = int(len(have) / len(needed) * 100)
        results.append((recipe, match_percent, missing))
    results.sort(key=lambda x: (-x[1], len(x[2])))
    return results


def print_recipe(recipe, match_percent, missing, have_products):
    print("\n" + "=" * 60)
    print("  " + recipe["name"].upper())
    print("=" * 60)
    print("Время: " + recipe["time"] + "   |   Порций: " + str(recipe["servings"]))
    print("Совпадение: " + str(match_percent) + "%")

    print("\nИнгредиенты:")
    for ing in recipe["ingredients"]:
        mark = "[+]" if normalize(ing) in have_products else "[-]"
        print("   " + mark + " " + ing)

    if recipe["optional"]:
        found_opt = [o for o in recipe["optional"] if normalize(o) in have_products]
        if found_opt:
            print("   У вас есть для вкуса: " + ", ".join(found_opt))

    if missing:
        print("\nНе хватает: " + ", ".join(sorted(missing)))

    print("\nПриготовление:")
    for i, step in enumerate(recipe["steps"], start=1):
        print("   " + str(i) + ". " + step)
    print()


